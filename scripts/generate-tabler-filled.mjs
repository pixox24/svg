// Pull Tabler filled geometry into the repo so Marks can paint it.
// Source: @tabler/icons 3.47.0, MIT. Brand icons are omitted.
// Run: node scripts/generate-tabler-filled.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '3.47.0';
const base = `https://cdn.jsdelivr.net/npm/@tabler/icons@${VERSION}/`;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lib = path.join(root, 'src', 'lib');

const SHELF = [
  'circle', 'square', 'square-rotated', 'hexagon', 'triangle',
  'pentagon', 'octagon', 'oval', 'diamond', 'heart',
  'star', 'moon', 'sun', 'cloud', 'flame',
  'flower', 'leaf', 'droplet', 'bolt', 'feather',
  'bookmark', 'bell', 'crown', 'flag', 'shield',
  'spade', 'clubs', 'paw', 'clover', 'cherry'
];

const meta = await (await fetch(base + 'icons.json')).json();
const nodes = await (await fetch(base + 'tabler-nodes-filled.json')).json();

function tagLine(item) {
  const tags = [];
  const seen = new Set();
  const add = (value) => {
    const word = String(value || '').trim().toLowerCase();
    if (!word || seen.has(word)) return;
    seen.add(word);
    tags.push(word);
  };
  add(item.category);
  for (const tag of item.tags || []) add(tag);
  return tags.slice(0, 12).join(' ');
}

const index = [];
const kept = {};
let painted = 0;
for (const name of Object.keys(meta).sort()) {
  const item = meta[name];
  if (!item.styles || !item.styles.filled) continue;
  if (item.category === 'Brand' || name.startsWith('brand-')) continue;
  const node = nodes[name];
  if (!node) {
    console.warn('missing node', name);
    continue;
  }
  const clean = node.map((part) => {
    const [tag, attrs = {}, children] = part;
    const next = {};
    for (const [key, value] of Object.entries(attrs)) {
      if (key === 'fill' || key === 'stroke' || key === 'stroke-width' || key === 'key' || key === 'class') {
        painted += 1;
        continue;
      }
      if (/[;{}]/.test(String(value))) console.warn('awkward attr', name, value);
      next[key] = value;
    }
    return children ? [tag, next, children] : [tag, next];
  });
  kept[name] = clean;
  index.push([name, tagLine(item)]);
}

const shelf = SHELF.map((name) => {
  const item = meta[name];
  if (!item || !item.styles || !item.styles.filled) throw new Error(`shelf icon unavailable: ${name}`);
  if (!kept[name]) throw new Error(`shelf icon dropped: ${name}`);
  return { name, tags: tagLine(item).split(' ').filter(Boolean), node: kept[name] };
});

const header = `// Filled icons from Tabler Icons ${VERSION}
// https://github.com/tabler/tabler-icons
// MIT License. Brand category omitted.
// Generated by scripts/generate-tabler-filled.mjs — do not edit by hand.
`;

const shelfFile = `${header}
export const TABLER_FILLED_VERSION = ${JSON.stringify(VERSION)};

export const FILLED_SHELF = ${JSON.stringify(shelf, null, 2)};

export const FILLED_INDEX = ${JSON.stringify(index)};
`;

fs.writeFileSync(path.join(lib, 'tablerFilled.js'), shelfFile);
fs.writeFileSync(path.join(lib, 'tablerFilledNodes.json'), JSON.stringify(kept));

const shelfBytes = fs.statSync(path.join(lib, 'tablerFilled.js')).size;
const nodeBytes = fs.statSync(path.join(lib, 'tablerFilledNodes.json')).size;
console.log(`shelf file ${(shelfBytes / 1024).toFixed(0)} KB`);
console.log(`nodes ${(nodeBytes / 1024).toFixed(0)} KB, icons ${index.length}, painted attrs ${painted}`);
